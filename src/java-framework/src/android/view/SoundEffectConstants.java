package android.view;
public class SoundEffectConstants {
    public static final int CLICK = 0, NAVIGATION_LEFT = 1, NAVIGATION_UP = 2, NAVIGATION_RIGHT = 3, NAVIGATION_DOWN = 4;
    public static int getContantForFocusDirection(int d) {
        switch (d) { case View.FOCUS_LEFT: return NAVIGATION_LEFT; case View.FOCUS_UP: case View.FOCUS_BACKWARD: return NAVIGATION_UP; case View.FOCUS_RIGHT: return NAVIGATION_RIGHT; case View.FOCUS_DOWN: case View.FOCUS_FORWARD: return NAVIGATION_DOWN; }
        throw new IllegalArgumentException("direction must be one of {FOCUS_UP, FOCUS_DOWN, FOCUS_LEFT, FOCUS_RIGHT, FOCUS_FORWARD, FOCUS_BACKWARD}.");
    }
    public static int getConstantForFocusDirection(int d, boolean repeat) {
        if (!repeat) return getContantForFocusDirection(d);
        switch (d) { case View.FOCUS_LEFT: return NAVIGATION_REPEAT_LEFT; case View.FOCUS_UP: case View.FOCUS_BACKWARD: return NAVIGATION_REPEAT_UP; case View.FOCUS_RIGHT: return NAVIGATION_REPEAT_RIGHT; case View.FOCUS_DOWN: case View.FOCUS_FORWARD: return NAVIGATION_REPEAT_DOWN; }
        throw new IllegalArgumentException("direction must be one of {FOCUS_UP, FOCUS_DOWN, FOCUS_LEFT, FOCUS_RIGHT, FOCUS_FORWARD, FOCUS_BACKWARD}.");
    }
    // ---- generated by tools/compat/fillmembers.py: the platform's members this class does not write (signatures only)
    public static final int NAVIGATION_REPEAT_DOWN = 8;
    public static final int NAVIGATION_REPEAT_LEFT = 5;
    public static final int NAVIGATION_REPEAT_RIGHT = 7;
    public static final int NAVIGATION_REPEAT_UP = 6;
    public static boolean isNavigationRepeat(int e) { return e >= NAVIGATION_REPEAT_LEFT && e <= NAVIGATION_REPEAT_DOWN; }
    public static int nextNavigationRepeatSoundEffectId() { return 0; }
    // ---- end of generated members
}
