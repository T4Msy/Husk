    public static final boolean addLinks(Spannable s, Pattern p, String defaultScheme, String[] schemes, MatchFilter mf, TransformFilter tf) {
        String[] all = new String[(schemes == null ? 0 : schemes.length) + 1];
        all[0] = defaultScheme == null ? "" : defaultScheme.toLowerCase(java.util.Locale.ROOT);
        for (int i = 1; i < all.length; i++) all[i] = schemes[i - 1] == null ? "" : schemes[i - 1].toLowerCase(java.util.Locale.ROOT);
        Matcher m = p.matcher(s);
        boolean any = false;
        while (m.find()) {
            int a = m.start(), b = m.end();
            if (mf != null && !mf.acceptMatch(s, a, b)) continue;
            String url = m.group(0);
            if (tf != null) url = tf.transformUrl(m, url);
            url = makeUrl(url, all);
            s.setSpan(new URLSpan(url), a, b, android.text.Spanned.SPAN_EXCLUSIVE_EXCLUSIVE);
            any = true;
        }
        return any;
    }
    /* the url with the first scheme unless it already starts with one of them (compared ignoring case, which the scheme keeps lower) */
    private static String makeUrl(String url, String[] schemes) {
        String lower = url.toLowerCase(java.util.Locale.ROOT);
        for (String sc : schemes) if (!sc.isEmpty() && lower.startsWith(sc)) return url.length() > sc.length() && !url.startsWith(sc) ? sc + url.substring(sc.length()) : url;
        if (lower.startsWith("http://") || lower.startsWith("https://") || lower.startsWith("rtsp://")) return url;
        return schemes[0] + url;
    }
